using System.Collections.Generic;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace HPD.Agent.Bots.SourceGenerator.Generators;

/// <summary>
/// Generates BotRegistry.g.cs — one assembly-scoped file listing every [HpdBot]
/// class. Used by MapHPDBots() to wire all adapters without reflection.
/// </summary>
internal static class RegistryGenerator
{
    public static void Generate(
        SourceProductionContext context,
        IReadOnlyList<BotInfo> adapters)
    {
        if (adapters.Count == 0) return;

        var source = BuildSource(adapters);
        context.AddSource("BotRegistry.g.cs",
            SourceText.From(source, Encoding.UTF8));
    }

    private static string BuildSource(IReadOnlyList<BotInfo> adapters)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using HPD.Agent.Bots;");
        sb.AppendLine("using HPD.Agent.Bots.AspNetCore;");
        sb.AppendLine("using Microsoft.AspNetCore.Builder;");
        sb.AppendLine("using Microsoft.AspNetCore.Routing;");
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        sb.AppendLine();
        sb.AppendLine("namespace HPD.Agent.Bots.Generated;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>AOT-safe catalog of all adapters registered in this assembly.</summary>");
        sb.AppendLine("internal static class BotRegistry");
        sb.AppendLine("{");
        sb.AppendLine("    public static readonly BotRegistration[] All =");
        sb.AppendLine("    [");

        foreach (var adapter in adapters)
        {
            var pascal = char.ToUpper(adapter.Name[0]) + adapter.Name.Substring(1);
            var mapExpr = $"{adapter.Namespace}.{adapter.ClassName}EndpointRouteBuilderExtensions.Map{pascal}Webhook(app, path ?? \"/webhooks/{adapter.Name}\")";
            sb.AppendLine($"        new BotRegistration(");
            sb.AppendLine($"            Name: \"{adapter.Name}\",");
            sb.AppendLine($"            BotType: typeof({adapter.Namespace}.{adapter.ClassName}),");
            sb.AppendLine($"            MapEndpoint: (app, path) => {mapExpr},");
            sb.AppendLine($"            DefaultPath: \"/webhooks/{adapter.Name}\"),");
        }

        sb.AppendLine("    ];");
        sb.AppendLine("}");

        return sb.ToString();
    }
}
