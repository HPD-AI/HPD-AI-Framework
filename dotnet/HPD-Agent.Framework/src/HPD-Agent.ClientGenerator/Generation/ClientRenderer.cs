using System.Text;
using System.Text.Json;
using HPD.Agent.SDK.Contract;

namespace HPD.Agent.ClientGenerator.Generation;

internal sealed class ClientRenderer(
    HpdSdkIr ir,
    CSharpNames names,
    string namespaceName)
{
    private readonly IReadOnlyDictionary<string, string> _services =
        RuntimeRenderer.ServicesFor(ir);

    public string RenderServices()
    {
        var builder = new StringBuilder()
            .AppendLine("// <auto-generated/>")
            .AppendLine("#nullable enable")
            .AppendLine("using System.Text.Json;")
            .Append(namespaceName == "HPD.Agent.Client" ? string.Empty : "using HPD.Agent.Client;\n")
            .AppendLine()
            .Append("namespace ").Append(namespaceName).AppendLine(";");

        foreach (var group in ir.Operations
                     .GroupBy(static operation => operation.Tag, StringComparer.Ordinal)
                     .OrderBy(static group => group.Key, StringComparer.Ordinal))
        {
            builder.AppendLine();
            RenderService(builder, group.Key, group.OrderBy(static operation => operation.OperationId).ToArray());
        }
        return builder.ToString();
    }

    private void RenderService(
        StringBuilder builder,
        string tag,
        IReadOnlyList<HpdOperationIr> operations)
    {
        var serviceName = _services[tag];
        builder.AppendLine("/// <summary>Generated operations for the declared HPD Agent resource family.</summary>")
            .Append("public sealed class ").Append(serviceName).AppendLine("(HpdAgentClient client)")
            .AppendLine("{")
            .AppendLine("    private readonly HpdAgentClient _client =")
            .AppendLine("        client ?? throw new ArgumentNullException(nameof(client));");
        foreach (var operation in operations)
        {
            builder.AppendLine();
            RenderOperation(builder, operation);
        }
        builder.AppendLine("}");
    }

    private void RenderOperation(StringBuilder builder, HpdOperationIr operation)
    {
        if (operation.ContentKind == "websocket")
        {
            RenderWebSocketConnection(builder, operation);
            return;
        }
        if (string.Equals(operation.OperationId, "UploadContent", StringComparison.Ordinal))
        {
            RenderUpload(builder, operation);
            return;
        }

        var parameters = BuildParameters(operation);
        var returnType = ReturnType(operation);
        var methodName = MethodName(operation.OperationId);
        builder.Append("    public ");
        if (operation.ContentKind == "sse")
            builder.Append("IAsyncEnumerable<HpdAgentSseMessage> ");
        else if (returnType is null)
            builder.Append("async Task ");
        else
            builder.Append("async Task<").Append(returnType).Append("> ");
        builder.Append(methodName).AppendLine("(");
        foreach (var parameter in parameters)
        {
            builder.Append("        ").Append(parameter.Type).Append(' ')
                .Append(parameter.Name);
            if (parameter.DefaultValue is not null)
                builder.Append(" = ").Append(parameter.DefaultValue);
            builder.AppendLine(",");
        }
        if (operation.ContentKind == "sse")
        {
            builder.AppendLine("        HpdAgentSseReconnectOptions? reconnectOptions = null,")
                .AppendLine("        Action<HpdAgentSseReconnectDiagnostic>? onReconnect = null,");
            builder.AppendLine("        string? lastEventId = null,");
        }
        builder.AppendLine("        CancellationToken cancellationToken = default)");
        builder.AppendLine("    {");
        RenderQuery(builder, parameters);
        var pathExpression = PathExpression(operation, parameters);
        if (operation.ContentKind == "sse")
        {
            builder.Append("        return _client.Transport.StreamSseAsync(")
                .Append(pathExpression)
                .AppendLine(", query, lastEventId, reconnectOptions, onReconnect, cancellationToken);");
        }
        else if (string.Equals(operation.SuccessMediaType, "application/octet-stream", StringComparison.Ordinal))
        {
            builder.Append("        return await _client.Transport.SendBytesAsync(")
                .Append(HttpMethodExpression(operation.Method)).Append(", ")
                    .Append(pathExpression).Append(", query, ")
                    .Append(operation.ReplaySafe ? "true" : "false")
                    .AppendLine(", cancellationToken)")
                .AppendLine("            .ConfigureAwait(false);");
        }
        else
        {
            RenderRequestBody(builder, parameters);
            if (returnType is null)
            {
                builder.Append("        await _client.Transport.SendAsync(")
                    .Append(HttpMethodExpression(operation.Method)).Append(", ")
                    .Append(pathExpression).Append(", query, requestBody, ")
                    .Append(operation.ReplaySafe ? "true" : "false")
                    .AppendLine(", cancellationToken)")
                    .AppendLine("            .ConfigureAwait(false);");
            }
            else
            {
                builder.Append("        return await _client.Transport.SendJsonAsync<")
                    .Append(returnType).AppendLine(">(")
                    .Append("            ").Append(HttpMethodExpression(operation.Method)).Append(", ")
                    .Append(pathExpression).Append(", query, requestBody, ")
                    .Append(operation.ReplaySafe ? "true" : "false").AppendLine(",")
                    .Append("            HpdAgentJsonContext.Default.")
                    .Append(CSharpNames.TypeInfoName(returnType)).AppendLine(",")
                    .AppendLine("            cancellationToken)")
                    .AppendLine("            .ConfigureAwait(false);");
            }
        }
        builder.AppendLine("    }");
        if (operation.Method == "GET" &&
            operation.HasNotFoundResponse &&
            returnType is not null &&
            returnType is not "byte[]" and not "JsonElement")
        {
            builder.AppendLine();
            RenderNotFoundDefaultMethod(builder, operation, parameters, returnType);
        }
    }

    private static void RenderNotFoundDefaultMethod(
        StringBuilder builder,
        HpdOperationIr operation,
        IReadOnlyList<MethodParameter> parameters,
        string returnType)
    {
        builder.Append("    public async Task<").Append(returnType).AppendLine("?> Try" +
            (operation.OperationId.EndsWith("Async", StringComparison.Ordinal)
                ? operation.OperationId
                : operation.OperationId + "Async") + "(");
        foreach (var parameter in parameters)
        {
            builder.Append("        ").Append(parameter.Type).Append(' ')
                .Append(parameter.Name);
            if (parameter.DefaultValue is not null)
                builder.Append(" = ").Append(parameter.DefaultValue);
            builder.AppendLine(",");
        }
        builder.AppendLine("        CancellationToken cancellationToken = default)")
            .AppendLine("    {");
        RenderQuery(builder, parameters);
        builder.Append("        return await _client.Transport.SendJsonOrDefaultAsync<")
            .Append(returnType).AppendLine(">(")
            .Append("            HttpMethod.Get, ")
            .Append(PathExpression(operation, parameters))
            .AppendLine(", query,")
            .Append("            HpdAgentJsonContext.Default.")
            .Append(CSharpNames.TypeInfoName(returnType)).AppendLine(",")
            .AppendLine("            cancellationToken)")
            .AppendLine("            .ConfigureAwait(false);")
            .AppendLine("    }");
    }

    private void RenderWebSocketConnection(StringBuilder builder, HpdOperationIr operation)
    {
        var parameters = BuildParameters(operation)
            .Where(static parameter => parameter.Location is "path" or "query")
            .ToArray();
        builder.Append("    public HpdAgentClientToolProviderClient ")
            .Append(operation.OperationId).AppendLine("(");
        foreach (var parameter in parameters)
        {
            builder.Append("        ").Append(parameter.Type).Append(' ')
                .Append(parameter.Name);
            if (parameter.DefaultValue is not null)
                builder.Append(" = ").Append(parameter.DefaultValue);
            builder.AppendLine(",");
        }
        builder
            .AppendLine("        HpdAgentClientToolProviderIdentity identity,")
            .AppendLine("        HpdAgentClientAppProvider? appProvider = null,")
            .AppendLine("        IReadOnlyList<JsonElement>? clientToolHarnesses = null,")
            .AppendLine("        JsonElement? context = null,")
            .AppendLine("        string readiness = \"Ready\",")
            .AppendLine("        JsonElement? metadata = null)")
            .AppendLine("    {")
            .AppendLine("        ArgumentNullException.ThrowIfNull(identity);")
            .Append("        var endpoint = new Uri(_client.BaseAddress.ToString().TrimEnd('/') + ")
            .Append(PathExpression(operation, parameters)).AppendLine(");");
        builder
            .AppendLine("        return new HpdAgentClientToolProviderClient(")
            .AppendLine("            new HpdAgentClientToolProviderOptions(endpoint)")
            .AppendLine("            {")
            .AppendLine("                Identity = identity,")
            .AppendLine("                AppProvider = appProvider,")
            .AppendLine("                ClientToolHarnesses = clientToolHarnesses,")
            .AppendLine("                Context = context,")
            .AppendLine("                Readiness = readiness,")
            .AppendLine("                Metadata = metadata,")
            .AppendLine("                Headers = _client.DefaultHeaders")
            .AppendLine("            });")
            .AppendLine("    }");
    }

    private void RenderUpload(StringBuilder builder, HpdOperationIr operation)
    {
        var responseType = ReturnType(operation) ?? "JsonElement";
        var pathExpression = PathExpression(operation, BuildParameters(operation));
        builder.Append("    public async Task<").Append(responseType).AppendLine("> UploadContentAsync(")
            .AppendLine("        string sid,")
            .AppendLine("        string bid,")
            .AppendLine("        Stream file,")
            .AppendLine("        string fileName,")
            .AppendLine("        string contentType = \"application/octet-stream\",")
            .AppendLine("        CancellationToken cancellationToken = default)")
            .AppendLine("    {")
            .Append("        return await _client.Transport.SendMultipartJsonAsync<")
            .Append(responseType).AppendLine(">(")
            .Append("            ").Append(pathExpression).AppendLine(", query: null, file, \"file\", fileName,")
            .AppendLine("            contentType, HpdAgentJsonContext.Default." +
                CSharpNames.TypeInfoName(responseType) + ",")
            .AppendLine("            cancellationToken)")
            .AppendLine("            .ConfigureAwait(false);")
            .AppendLine("    }");
    }

    private IReadOnlyList<MethodParameter> BuildParameters(HpdOperationIr operation)
    {
        var result = new List<MethodParameter>();
        var used = new HashSet<string>(StringComparer.Ordinal) { "cancellationToken", "requestBody", "query" };
        foreach (var parameter in operation.Parameters)
        {
            if (string.Equals(parameter.Location, "header", StringComparison.Ordinal))
                continue;
            var name = Unique(CSharpNames.ParameterIdentifier(parameter.Name), used);
            var optional = !parameter.Required;
            var type = names.MapType(parameter.Type, optional);
            result.Add(new MethodParameter(
                parameter.Name,
                parameter.Location,
                name,
                type,
                optional && type.EndsWith('?') ? "null" : null));
        }

        if (operation.RequestBody is { } requestBody &&
            string.Equals(operation.OperationId, "UploadContent", StringComparison.Ordinal))
        {
            return result;
        }
        if (operation.RequestBody is not null)
        {
            var type = RequestBodyType(operation);
            var name = Unique("input", used);
            result.Add(new MethodParameter(
                "body",
                "body",
                name,
                type,
                !operation.RequestBody.Required && type.EndsWith('?') ? "null" : null));
        }
        // C# requires every optional parameter to follow required parameters.
        // Keep declaration order stable within each group for deterministic output.
        return result
            .OrderBy(static parameter => parameter.DefaultValue is null ? 0 : 1)
            .ToArray();
    }

    private static void RenderQuery(StringBuilder builder, IReadOnlyList<MethodParameter> parameters)
    {
        var queryParameters = parameters.Where(static parameter => parameter.Location == "query").ToArray();
        builder.AppendLine("        var query = new Dictionary<string, string?>(StringComparer.Ordinal);");
        foreach (var parameter in queryParameters)
        {
            if (parameter.DefaultValue is null)
            {
                builder.Append("        query[").Append(Quote(parameter.WireName)).Append("] = ")
                    .Append("HpdAgentClientHelpers.Query(").Append(parameter.Name).AppendLine(");");
            }
            else
            {
                builder.Append("        if (").Append(parameter.Name).AppendLine(" is not null)")
                    .Append("            query[").Append(Quote(parameter.WireName)).Append("] = ")
                    .Append("HpdAgentClientHelpers.Query(").Append(parameter.Name).AppendLine(");");
            }
        }
    }

    private static void RenderRequestBody(
        StringBuilder builder,
        IReadOnlyList<MethodParameter> parameters)
    {
        var body = parameters.SingleOrDefault(static parameter => parameter.Location == "body");
        if (body is null)
        {
            builder.AppendLine("        JsonElement? requestBody = null;");
            return;
        }

        if (string.Equals(body.Type.TrimEnd('?'), "JsonElement", StringComparison.Ordinal))
        {
            builder.Append("        JsonElement? requestBody = ").Append(body.Name).AppendLine(";");
            return;
        }

        var typeInfoName = CSharpNames.TypeInfoName(body.Type.TrimEnd('?'));
        builder.Append("        JsonElement? requestBody = ").Append(body.Name)
            .Append(" is null ? null : JsonSerializer.SerializeToElement(")
            .Append(body.Name).Append(", HpdAgentJsonContext.Default.")
            .Append(typeInfoName).AppendLine(");");
    }

    private static string PathExpression(
        HpdOperationIr operation,
        IReadOnlyList<MethodParameter> parameters)
    {
        var pathParameters = parameters
            .Where(static parameter => parameter.Location == "path")
            .ToDictionary(static parameter => parameter.WireName, StringComparer.Ordinal);
        var path = operation.Path;
        foreach (var parameter in pathParameters)
        {
            path = path.Replace(
                "{" + parameter.Key + "}",
                "{HpdAgentClientHelpers.Path(" + parameter.Value.Name + ")}",
                StringComparison.Ordinal);
        }
        return "$\"" + path.Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";
    }

    private string RequestBodyType(HpdOperationIr operation)
    {
        if (string.Equals(operation.OperationId, "SubmitAgentInput", StringComparison.Ordinal) ||
            string.Equals(operation.OperationId, "SubmitControlledSubAgentInput", StringComparison.Ordinal))
        {
            return "HpdAgentInputEvent";
        }
        if (string.Equals(operation.OperationId, "RespondToAgentRequest", StringComparison.Ordinal))
            return "HpdAgentResponseInput";
        var type = operation.RequestBody?.Type
            ?? throw new InvalidOperationException($"Operation '{operation.OperationId}' has no request body.");
        return names.MapType(type);
    }

    private string? ReturnType(HpdOperationIr operation)
    {
        if (operation.ContentKind == "sse")
            return null;
        if (string.Equals(operation.OperationId, "RespondToAgentRequest", StringComparison.Ordinal))
            return "HpdAgentResponseResult";
        if (string.Equals(operation.OperationId, "SubmitAgentInput", StringComparison.Ordinal) ||
            string.Equals(operation.OperationId, "SubmitControlledSubAgentInput", StringComparison.Ordinal))
            return "HpdAgentInputSubmissionResult";
        if (operation.SuccessType is null)
            return null;
        if (string.Equals(operation.SuccessMediaType, "application/octet-stream", StringComparison.Ordinal))
            return "byte[]";
        return names.MapType(operation.SuccessType);
    }

    private static string MethodName(string operationId) =>
        operationId.EndsWith("Async", StringComparison.Ordinal)
            ? operationId
            : operationId + "Async";

    private static string HttpMethodExpression(string method) =>
        method switch
        {
            "GET" => "HttpMethod.Get",
            "POST" => "HttpMethod.Post",
            "PUT" => "HttpMethod.Put",
            "PATCH" => "HttpMethod.Patch",
            "DELETE" => "HttpMethod.Delete",
            "HEAD" => "HttpMethod.Head",
            "OPTIONS" => "HttpMethod.Options",
            _ => throw new InvalidOperationException($"Unsupported HTTP method '{method}'.")
        };

    private static string Unique(string candidate, HashSet<string> used)
    {
        if (used.Add(candidate))
            return candidate;
        for (var suffix = 2; ; suffix++)
        {
            var next = candidate + suffix;
            if (used.Add(next))
                return next;
        }
    }

    private static string Quote(string value) =>
        JsonSerializer.Serialize(value);

    private sealed record MethodParameter(
        string WireName,
        string Location,
        string Name,
        string Type,
        string? DefaultValue);
}
