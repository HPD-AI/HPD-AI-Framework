using System.Text;
using System.Text.Json;
using HPD.Agent.ClientGenerator.RuntimeCatalog;
using HPD.Agent.SDK.Contract;

namespace HPD.Agent.ClientGenerator.Generation;

internal sealed class RuntimePayloadRenderer(
    RuntimeCatalogIr catalog,
    string namespaceName)
{
    private readonly IReadOnlyList<PayableSchema> _modeled = CreateModels(catalog);

    public string Render()
    {
        var builder = new StringBuilder()
            .AppendLine("// <auto-generated/>")
            .AppendLine("#nullable enable")
            .AppendLine("using System.Text.Json;")
            .AppendLine("using System.Text.Json.Serialization;")
            .AppendLine()
            .Append("namespace ").Append(namespaceName).AppendLine(";")
            .AppendLine()
            .AppendLine("/// <summary>Stable keys for schemas present when the SDK was generated.</summary>")
            .AppendLine("public static class HpdRuntimeExtensionSchemaKeys")
            .AppendLine("{");
        foreach (var schema in catalog.Schemas)
        {
            builder.Append("    public const string ").Append(ConstantName(schema))
                .Append(" = ").Append(Quote(schema.Key)).AppendLine(";");
        }
        builder.AppendLine("}")
            .AppendLine()
            .AppendLine("/// <summary>Strongly typed payload generated from a runtime extension catalog.</summary>")
            .AppendLine("public abstract partial record HpdRuntimeExtensionPayload;");

        foreach (var schema in _modeled)
        {
            builder.AppendLine();
            RenderModel(builder, schema);
        }

        RenderContext(builder);
        RenderCodec(builder);
        return builder.ToString();
    }

    private void RenderModel(StringBuilder builder, PayableSchema schema)
    {
        builder.Append("public sealed partial record ").Append(schema.ModelName)
            .AppendLine(" : HpdRuntimeExtensionPayload")
            .AppendLine("{");
        var required = schema.Schema.TryGetProperty("required", out var requiredElement) &&
                       requiredElement.ValueKind == JsonValueKind.Array
            ? requiredElement.EnumerateArray()
                .Select(static item => item.GetString())
                .Where(static item => item is not null)
                .Select(static item => item!)
                .ToHashSet(StringComparer.Ordinal)
            : new HashSet<string>(StringComparer.Ordinal);
        var usedNames = new HashSet<string>(StringComparer.Ordinal);
        if (schema.Schema.TryGetProperty("properties", out var properties) &&
            properties.ValueKind == JsonValueKind.Object)
        {
            foreach (var property in properties.EnumerateObject())
            {
                var name = UniqueName(CSharpNames.PropertyIdentifier(property.Name), usedNames);
                var isRequired = required.Contains(property.Name);
                var type = MapValue(schema.Root, property.Value, optional: !isRequired);
                builder.Append("    [JsonPropertyName(").Append(Quote(property.Name)).AppendLine(")]")
                    .Append("    public ");
                if (isRequired)
                    builder.Append("required ");
                builder.Append(type).Append(' ').Append(name).AppendLine(" { get; init; }")
                    .AppendLine();
            }
        }
        builder.AppendLine("}");
    }

    private void RenderContext(StringBuilder builder)
    {
        builder.AppendLine()
            .AppendLine("[JsonSourceGenerationOptions(")
            .AppendLine("    PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase,")
            .AppendLine("    DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull)]")
            .AppendLine("[JsonSerializable(typeof(JsonElement))]");
        foreach (var schema in _modeled)
            builder.Append("[JsonSerializable(typeof(").Append(schema.ModelName).AppendLine("))]");
        builder.AppendLine("internal sealed partial class RuntimePayloadJsonContext : JsonSerializerContext;");
    }

    private void RenderCodec(StringBuilder builder)
    {
        builder.AppendLine()
            .AppendLine("/// <summary>Typed conversion between runtime payload models and stable envelopes.</summary>")
            .AppendLine("public static class HpdRuntimeExtensionPayloadCodec")
            .AppendLine("{")
            .Append("    public const string CatalogDigest = ").Append(Quote(catalog.Digest)).AppendLine(";")
            .AppendLine()
            .AppendLine("    public static HpdRuntimeExtensionPayload? Decode(RuntimeAgentLiveEvent value) =>")
            .AppendLine("        Decode(value.ExtensionNamespace, value.SchemaName, value.SchemaVersion, value.SchemaDigest, value.Payload);")
            .AppendLine()
            .AppendLine("    public static HpdRuntimeExtensionPayload? Decode(RuntimeAgentDurableEvent value) =>")
            .AppendLine("        Decode(value.ExtensionNamespace, value.SchemaName, value.SchemaVersion, value.SchemaDigest, value.Payload);")
            .AppendLine()
            .AppendLine("    public static HpdRuntimeExtensionPayload? Decode(RuntimeAgentInputEvent value) =>")
            .AppendLine("        Decode(value.ExtensionNamespace, value.SchemaName, value.SchemaVersion, value.SchemaDigest, value.Payload);")
            .AppendLine()
            .AppendLine("    public static RuntimeAgentLiveEvent CreateLiveEvent(HpdRuntimeExtensionPayload payload)")
            .AppendLine("    {")
            .AppendLine("        var value = Encode(payload);")
            .AppendLine("        return new RuntimeAgentLiveEvent")
            .AppendLine("        {")
            .AppendLine("            ExtensionNamespace = value.Namespace,")
            .AppendLine("            SchemaName = value.Name,")
            .AppendLine("            SchemaVersion = value.Version,")
            .AppendLine("            SchemaDigest = value.Digest,")
            .AppendLine("            Payload = value.Payload")
            .AppendLine("        };")
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    public static RuntimeAgentDurableEvent CreateDurableEvent(HpdRuntimeExtensionPayload payload)")
            .AppendLine("    {")
            .AppendLine("        var value = Encode(payload);")
            .AppendLine("        return new RuntimeAgentDurableEvent")
            .AppendLine("        {")
            .AppendLine("            ExtensionNamespace = value.Namespace,")
            .AppendLine("            SchemaName = value.Name,")
            .AppendLine("            SchemaVersion = value.Version,")
            .AppendLine("            SchemaDigest = value.Digest,")
            .AppendLine("            Payload = value.Payload")
            .AppendLine("        };")
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    public static RuntimeAgentInputEvent CreateInput(HpdRuntimeExtensionPayload payload)")
            .AppendLine("    {")
            .AppendLine("        var value = Encode(payload);")
            .AppendLine("        return new RuntimeAgentInputEvent")
            .AppendLine("        {")
            .AppendLine("            ExtensionNamespace = value.Namespace,")
            .AppendLine("            SchemaName = value.Name,")
            .AppendLine("            SchemaVersion = value.Version,")
            .AppendLine("            SchemaDigest = value.Digest,")
            .AppendLine("            Payload = value.Payload")
            .AppendLine("        };")
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    private static HpdRuntimeExtensionPayload? Decode(")
            .AppendLine("        string extensionNamespace,")
            .AppendLine("        string name,")
            .AppendLine("        int version,")
            .AppendLine("        string digest,")
            .AppendLine("        JsonElement payload)")
            .AppendLine("    {");
        foreach (var schema in _modeled)
        {
            builder.Append("        if (extensionNamespace == ").Append(Quote(schema.Namespace))
                .Append(" && name == ").Append(Quote(schema.Name))
                .Append(" && version == ").Append(schema.Version)
                .Append(" && digest == ").Append(Quote(schema.Digest)).AppendLine(")");
            builder.Append("            return JsonSerializer.Deserialize(payload, RuntimePayloadJsonContext.Default.")
                .Append(schema.ModelName).AppendLine(");");
        }
        builder.AppendLine("        return null;")
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    private static (string Namespace, string Name, int Version, string Digest, JsonElement Payload) Encode(")
            .AppendLine("        HpdRuntimeExtensionPayload payload)")
            .AppendLine("    {")
            .AppendLine("        ArgumentNullException.ThrowIfNull(payload);")
            .AppendLine("        return payload switch")
            .AppendLine("        {");
        foreach (var schema in _modeled)
        {
            builder.Append("            ").Append(schema.ModelName).Append(" value => (")
                .Append(Quote(schema.Namespace)).Append(", ")
                .Append(Quote(schema.Name)).Append(", ")
                .Append(schema.Version).Append(", ")
                .Append(Quote(schema.Digest)).AppendLine(",")
                .Append("                JsonSerializer.SerializeToElement(value, RuntimePayloadJsonContext.Default.")
                .Append(schema.ModelName).AppendLine(")),");
        }
        builder.AppendLine("            _ => throw new InvalidOperationException(\"The runtime payload is not part of this generated catalog.\")")
            .AppendLine("        };")
            .AppendLine("    }")
            .AppendLine("}");
    }

    private static IReadOnlyList<PayableSchema> CreateModels(RuntimeCatalogIr catalog)
    {
        var result = new List<PayableSchema>();
        var used = new HashSet<string>(StringComparer.Ordinal);
        foreach (var schema in catalog.Schemas)
        {
            var resolved = Resolve(schema.PayloadSchema, schema.PayloadSchema);
            if (!IsObject(resolved))
                continue;
            var candidate = "RuntimePayload" + CSharpNames.TypeIdentifier(
                schema.Namespace + "." + schema.Name + ".V" + schema.Version);
            if (!used.Add(candidate))
                candidate += "_" + Math.Abs(schema.Key.GetHashCode()).ToString("x8");
            result.Add(new PayableSchema(
                schema,
                resolved,
                schema.PayloadSchema,
                candidate));
        }
        return result;
    }

    private static string MapValue(JsonElement root, JsonElement schema, bool optional, int depth = 0)
    {
        if (depth > 32)
            return "JsonElement";
        schema = Resolve(schema, root);
        if (schema.TryGetProperty("oneOf", out _) ||
            schema.TryGetProperty("anyOf", out _) ||
            schema.TryGetProperty("allOf", out _))
        {
            return Nullable("JsonElement", optional);
        }
        if (!schema.TryGetProperty("type", out var typeElement))
            return Nullable("JsonElement", optional);
        var type = typeElement.ValueKind == JsonValueKind.String
            ? typeElement.GetString()
            : typeElement.ValueKind == JsonValueKind.Array
                ? typeElement.EnumerateArray().Select(static item => item.GetString())
                    .FirstOrDefault(static item => item != "null")
                : null;
        var nullable = optional ||
                       typeElement.ValueKind == JsonValueKind.Array &&
                       typeElement.EnumerateArray().Any(static item => item.GetString() == "null");
        return type switch
        {
            "string" => Nullable("string", nullable),
            "integer" => Nullable(
                schema.TryGetProperty("format", out var integerFormat) &&
                integerFormat.GetString() == "int64" ? "long" : "int",
                nullable),
            "number" => Nullable(
                schema.TryGetProperty("format", out var numberFormat) &&
                numberFormat.GetString() == "float" ? "float" : "double",
                nullable),
            "boolean" => Nullable("bool", nullable),
            "array" => Nullable(
                "List<" + (schema.TryGetProperty("items", out var items)
                    ? MapValue(root, items, optional: false, depth + 1)
                    : "JsonElement") + ">",
                nullable),
            "object" when schema.TryGetProperty("additionalProperties", out var additional) &&
                          additional.ValueKind == JsonValueKind.Object =>
                Nullable("Dictionary<string, " + MapValue(root, additional, optional: false, depth + 1) + ">", nullable),
            _ => Nullable("JsonElement", nullable)
        };
    }

    private static JsonElement Resolve(JsonElement schema, JsonElement root)
    {
        if (!schema.TryGetProperty("$ref", out var reference) ||
            reference.GetString() is not { } refText ||
            !refText.StartsWith("#/", StringComparison.Ordinal))
        {
            return schema;
        }
        var current = root;
        foreach (var segment in refText[2..].Split('/'))
        {
            var name = segment.Replace("~1", "/", StringComparison.Ordinal)
                .Replace("~0", "~", StringComparison.Ordinal);
            if (current.ValueKind != JsonValueKind.Object ||
                !current.TryGetProperty(name, out current))
            {
                return schema;
            }
        }
        return current;
    }

    private static bool IsObject(JsonElement schema) =>
        schema.TryGetProperty("type", out var type) && type.GetString() == "object" ||
        schema.TryGetProperty("properties", out _);

    private static string Nullable(string type, bool nullable) =>
        nullable && !type.EndsWith('?') ? type + "?" : type;

    private static string UniqueName(string value, HashSet<string> used)
    {
        if (used.Add(value))
            return value;
        for (var suffix = 2; ; suffix++)
        {
            var next = value + suffix;
            if (used.Add(next))
                return next;
        }
    }

    private static string ConstantName(RuntimeCatalogSchemaIr schema) =>
        "Schema" + CSharpNames.TypeIdentifier(schema.Namespace + "." + schema.Name + ".V" + schema.Version);

    private static string Quote(string value) => JsonSerializer.Serialize(value);

    private sealed record PayableSchema(
        RuntimeCatalogSchemaIr Source,
        JsonElement Schema,
        JsonElement Root,
        string ModelName)
    {
        public string Key => Source.Key;
        public string Namespace => Source.Namespace;
        public string Name => Source.Name;
        public int Version => Source.Version;
        public string Digest => Source.PayloadSchemaDigest;
    }
}
