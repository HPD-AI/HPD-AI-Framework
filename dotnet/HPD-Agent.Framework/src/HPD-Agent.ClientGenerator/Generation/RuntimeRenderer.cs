            .AppendLine("        HpdAgentSseReconnectOptions? reconnectOptions = null,")
            .AppendLine("        Action<HpdAgentSseReconnectDiagnostic>? onReconnect = null,")
            .AppendLine("        CancellationToken cancellationToken = default)")
            .AppendLine("    {")
            .AppendLine("        if (Interlocked.CompareExchange(ref _running, 1, 0) != 0)")
            .AppendLine("            throw new InvalidOperationException(\"This live event client is already observing.\");")
            .AppendLine("        var applied = after ?? HpdAgentSseAppliedCursor.Initial;")
            .AppendLine("        var state = new HpdAgentSseState(applied);")
            .AppendLine("        try")
            .AppendLine("        {")
            .AppendLine("            await foreach (var message in _client.AgentEvents.ObserveLiveEventsWithSseAsync(")
            .AppendLine("                agentId,")
            .AppendLine("                bid,")
            .AppendLine("                sid,")
            .AppendLine("                after: applied.ToString(),");
        if (supportsHierarchy)
            builder.AppendLine("                hierarchy: hierarchy,");
        builder
            .AppendLine("                reconnectOptions: reconnectOptions,")
            .AppendLine("                onReconnect: onReconnect,")
            .AppendLine("                lastEventId: applied.ToString(),")
            .AppendLine("                cancellationToken: cancellationToken).ConfigureAwait(false))")
            .AppendLine("            {")
            .AppendLine("                await DispatchAsync(state, agentId, bid, sid, message, cancellationToken)")
            .AppendLine("                    .ConfigureAwait(false);")
            .AppendLine("            }")
            .AppendLine("        }")
            .AppendLine("        catch (OperationCanceledException) when (cancellationToken.IsCancellationRequested)")
            .AppendLine("        {")
            .AppendLine("            throw;")
            .AppendLine("        }")
            .AppendLine("        catch (Exception exception)")
            .AppendLine("        {")
            .AppendLine("            await InvokeAsync(Snapshot(_errors), exception, cancellationToken)")
            .AppendLine("                .ConfigureAwait(false);")
            .AppendLine("            throw;")
            .AppendLine("        }")
            .AppendLine("        finally")
            .AppendLine("        {")
            .AppendLine("            Volatile.Write(ref _running, 0);")
            .AppendLine("        }")
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    private async ValueTask DispatchAsync(")
            .AppendLine("        HpdAgentSseState state,")
            .AppendLine("        string agentId,")
            .AppendLine("        string bid,")
            .AppendLine("        string sid,")
            .AppendLine("        HpdAgentSseMessage message,")
            .AppendLine("        CancellationToken cancellationToken)")
            .AppendLine("    {")
            .AppendLine("        await InvokeAsync(_raw, message, cancellationToken).ConfigureAwait(false);")
            .AppendLine("        if (!message.TryGetDelivery(out var delivery))")
            .AppendLine("        {")
            .AppendLine("            var decision = state.Apply(message, null);")
            .AppendLine("            if (decision is HpdAgentSseDecision.Committed or HpdAgentSseDecision.Live)")
            .AppendLine("                await InvokeAsync(Snapshot(_unknown), message, cancellationToken).ConfigureAwait(false);")
            .AppendLine("            if (decision == HpdAgentSseDecision.Control)")
            .AppendLine("                await InvokeAsync(_controls, message, cancellationToken).ConfigureAwait(false);")
            .AppendLine("            return;")
            .AppendLine("        }")
            .AppendLine()
            .AppendLine("        var sequence = ReadThreadSequenceNumber(message);")
            .AppendLine("        var classification = state.Apply(message, sequence);")
            .AppendLine("        if (classification == HpdAgentSseDecision.Duplicate)")
            .AppendLine("            return;")
            .AppendLine()
            .AppendLine("        var typedDelivery = delivery!;")
            .AppendLine("        var handlers = SnapshotHandlers(typedDelivery.Event.GetType());")
            .AppendLine("        foreach (var handler in handlers)")
            .AppendLine("            await handler(typedDelivery.Event, cancellationToken).ConfigureAwait(false);")
            .AppendLine("        foreach (var handler in Snapshot(_any))")
            .AppendLine("            await handler(typedDelivery, cancellationToken).ConfigureAwait(false);");
        if (hasClientTools)
        {
            builder
                .AppendLine()
                .AppendLine("        if (typedDelivery.Event is ")
                .Append(requestType).Append(" request &&")
                .AppendLine(" matchesResponderTarget(request, message))")
                .AppendLine("            await DispatchClientToolAsync(agentId, bid, sid, request, cancellationToken)")
                .AppendLine("                .ConfigureAwait(false);");
        }
        builder
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    private HpdAgentEventSubscription Add<T>(")
            .AppendLine("        List<T> handlers,")
            .AppendLine("        T handler)")
            .AppendLine("        where T : Delegate")
            .AppendLine("    {")
            .AppendLine("        ArgumentNullException.ThrowIfNull(handler);")
            .AppendLine("        lock (_sync)")
            .AppendLine("            handlers.Add(handler);")
            .AppendLine("        return new HpdAgentEventSubscription(() =>")
            .AppendLine("        {")
            .AppendLine("            lock (_sync)")
            .AppendLine("                handlers.Remove(handler);")
            .AppendLine("        });")
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    private List<Func<HpdAgentEvent, CancellationToken, ValueTask>> SnapshotHandlers(Type eventType)")
            .AppendLine("    {")
            .AppendLine("        lock (_sync)")
            .AppendLine("            return _typed.TryGetValue(eventType, out var handlers) ? [.. handlers] : [];")
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    private List<T> Snapshot<T>(List<T> handlers)")
            .AppendLine("    {")
            .AppendLine("        lock (_sync)")
            .AppendLine("            return [.. handlers];")
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    private static async ValueTask InvokeAsync<T>(")
            .AppendLine("        List<Func<T, CancellationToken, ValueTask>> handlers,")
            .AppendLine("        T value,")
            .AppendLine("        CancellationToken cancellationToken)")
            .AppendLine("    {")
            .AppendLine("        foreach (var handler in handlers.ToArray())")
            .AppendLine("            await handler(value, cancellationToken).ConfigureAwait(false);")
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    private static long? ReadThreadSequenceNumber(HpdAgentSseMessage message)")
            .AppendLine("    {")
            .AppendLine("        if (message.Data.ValueKind == System.Text.Json.JsonValueKind.Object &&")
            .AppendLine("            message.Data.TryGetProperty(\"event\", out var eventElement) &&")
            .AppendLine("            eventElement.ValueKind == System.Text.Json.JsonValueKind.Object &&")
            .AppendLine("            eventElement.TryGetProperty(\"threadSequenceNumber\", out var sequence) &&")
            .AppendLine("            sequence.TryGetInt64(out var value))")
            .AppendLine("            return value;")
            .AppendLine("        return null;")
            .AppendLine("    }");
        if (hasClientTools)
        {
            RenderClientToolDispatch(
                builder,
                requestType!,
                requestVariant!.ComponentId,
                outcomeVariant!.ComponentId,
                outcomeType!,
                outcomeEnumType!,
                argumentsType,
                targetType,
                targetIsJson,
                targetProperties);
        }
        builder.AppendLine("}");
    }

    private void RenderClientToolDispatch(
        StringBuilder builder,
        string requestType,
        string requestComponentId,
        string outcomeComponentId,
        string outcomeType,
        string outcomeEnumType,
        string argumentsType,
        string targetType,
        bool targetIsJson,
        IReadOnlySet<string> targetProperties)
    {
        var outcomeProperties = names.PropertyNames(outcomeComponentId);
        var augmentationType = outcomeProperties.Contains("augmentation")
            ? names.MapPropertyType(
                outcomeComponentId,
                "augmentation").TrimEnd('?')
            : "JsonElement";
        var augmentationIsJson =
            string.Equals(augmentationType, "JsonElement", StringComparison.Ordinal);
        builder
            .AppendLine()
            .AppendLine("    private bool matchesResponderTarget(" + requestType + " request, HpdAgentSseMessage message)")
            .AppendLine("    {")
            .AppendLine("        if (message.Data.ValueKind != System.Text.Json.JsonValueKind.Object ||")
            .AppendLine("            !message.Data.TryGetProperty(\"event\", out var eventElement) ||")
            .AppendLine("            !eventElement.TryGetProperty(\"target\", out var target) ||")
            .AppendLine("            target.ValueKind != System.Text.Json.JsonValueKind.Object)")
            .AppendLine("            return true;")
            .AppendLine("        var responder = _client.Responder;")
            .AppendLine("        if (target.TryGetProperty(\"responderId\", out var responderId) &&")
            .AppendLine("            responderId.ValueKind == System.Text.Json.JsonValueKind.String &&")
            .AppendLine("            !string.Equals(responderId.GetString(), responder.ResponderId, StringComparison.Ordinal))")
            .AppendLine("            return false;")
            .AppendLine("        if (target.TryGetProperty(\"responderGroup\", out var responderGroup) &&")
            .AppendLine("            responderGroup.ValueKind == System.Text.Json.JsonValueKind.String &&")
            .AppendLine("            !responder.ResponderGroups.Contains(responderGroup.GetString()!, StringComparer.Ordinal))")
            .AppendLine("            return false;")
            .AppendLine("        if (target.TryGetProperty(\"requiredCapabilities\", out var required) &&")
            .AppendLine("            required.ValueKind == System.Text.Json.JsonValueKind.Array)")
            .AppendLine("        {")
            .AppendLine("            var capabilities = responder.Capabilities")
            .AppendLine("                .Concat(Tools.Capabilities)")
            .AppendLine("                .ToHashSet(StringComparer.Ordinal);")
            .AppendLine("            foreach (var capability in required.EnumerateArray())")
            .AppendLine("            {")
            .AppendLine("                if (capability.ValueKind != System.Text.Json.JsonValueKind.String ||")
            .AppendLine("                    !capabilities.Contains(capability.GetString()!))")
            .AppendLine("                    return false;")
            .AppendLine("            }")
            .AppendLine("        }")
            .AppendLine("        return true;")
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    private async ValueTask DispatchClientToolAsync(")
            .AppendLine("        string agentId,")
            .AppendLine("        string bid,")
            .AppendLine("        string sid,")
            .AppendLine("        " + requestType + " request,")
            .AppendLine("        CancellationToken cancellationToken)")
            .AppendLine("    {")
            .AppendLine("        var invocation = new HpdAgentClientToolInvocation(")
            .AppendLine("            request.RequestId,")
            .AppendLine("            request.ToolName,")
            .AppendLine("            request.CallId,")
            .AppendLine(string.Equals(argumentsType, "JsonElement", StringComparison.Ordinal)
                ? "            request.Arguments,"
                : "            JsonSerializer.SerializeToElement(request.Arguments, HpdAgentJsonContext.Default." + CSharpNames.TypeInfoName(argumentsType) + "),")
            .AppendLine("            request.Description,")
            .AppendLine(targetIsJson
                ? "            request.Target,"
                : "            request.Target is null ? null : JsonSerializer.SerializeToElement(request.Target, HpdAgentJsonContext.Default." + CSharpNames.TypeInfoName(targetType) + "),")
            .AppendLine("            request.ResponsePolicy);")
            .AppendLine("        var result = await Tools.InvokeAsync(invocation, cancellationToken).ConfigureAwait(false);")
            .AppendLine("        var responder = _client.Responder;")
            .AppendLine("        var response = new " + outcomeType)
            .AppendLine("        {")
            .AppendLine("            RequestId = request.RequestId,")
            .AppendLine("            Outcome = new " + outcomeEnumType + "(result.Outcome),");
        AppendInitializerIfPresent(
            builder,
            outcomeProperties,
            "content",
            "Content = result.Content");
        AppendInitializerIfPresent(
            builder,
            outcomeProperties,
            "errorMessage",
            "ErrorMessage = result.ErrorMessage");
        AppendInitializerIfPresent(
            builder,
            outcomeProperties,
            "clientOperationId",
            "ClientOperationId = result.ClientOperationId");
        AppendInitializerIfPresent(
            builder,
            outcomeProperties,
            "operationKind",
            "OperationKind = result.OperationKind");
        AppendInitializerIfPresent(
            builder,
            outcomeProperties,
            "operationCapabilities",
            "OperationCapabilities = result.OperationCapabilities");
        if (outcomeProperties.Contains("augmentation"))
        {
            builder.AppendLine(augmentationIsJson
                ? "            Augmentation = result.Augmentation,"
                : "            Augmentation = result.Augmentation is { } augmentationValue ? JsonSerializer.Deserialize(augmentationValue, HpdAgentJsonContext.Default." +
                  CSharpNames.TypeInfoName(augmentationType) + ") : null,");
        }
        AppendInitializerIfPresent(
            builder,
            outcomeProperties,
            "responderId",
            "ResponderId = responder.ResponderId");
        AppendInitializerIfPresent(
            builder,
            outcomeProperties,
            "responderGroup",
            "ResponderGroup = responder.ResponderGroups.FirstOrDefault()");
        AppendInitializerIfPresent(
            builder,
            outcomeProperties,
            "capabilities",
            "Capabilities = responder.Capabilities.Concat(Tools.Capabilities).Distinct(StringComparer.Ordinal).ToList()");
        builder
            .AppendLine("        };")
            .AppendLine("        await _client.AgentInteractions.RespondToAgentRequestAsync(")
            .AppendLine("            agentId, bid, sid, response, cancellationToken).ConfigureAwait(false);")
            .AppendLine("    }");
    }

    private static void AppendInitializerIfPresent(
        StringBuilder builder,
        IReadOnlySet<string> properties,
        string wireName,
        string statement)
    {
        if (properties.Contains(wireName))
            builder.Append("            ").Append(statement).AppendLine(",");
    }

    public static IReadOnlyDictionary<string, string> ServicesFor(HpdSdkIr ir)
    {
        var result = new Dictionary<string, string>(StringComparer.Ordinal);
        var used = new HashSet<string>(StringComparer.Ordinal);
        foreach (var tag in ir.Operations.Select(static operation => operation.Tag)
                     .Distinct(StringComparer.Ordinal)
                     .OrderBy(static tag => tag, StringComparer.Ordinal))
        {
            var candidate = CSharpNames.TypeIdentifier(tag) + "Client";
            if (!used.Add(candidate))
                candidate += "Api";
            result.Add(tag, candidate);
        }
        return result;
    }

    private IReadOnlyDictionary<string, string> Services() =>
        ServicesFor(ir);

