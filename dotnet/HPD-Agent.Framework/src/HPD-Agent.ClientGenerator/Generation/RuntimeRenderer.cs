using HPD.Agent.SDK.Contract;

namespace HPD.Agent.ClientGenerator.Generation;

internal sealed class RuntimeRenderer(
    HpdSdkIr ir,
    CSharpNames names,
    string namespaceName)
{
    public string RenderRuntime()
    {
        var hasChat = CanRenderChat();
        var builder = new StringBuilder()
            .AppendLine("// <auto-generated/>")
            .AppendLine("#nullable enable")
            .AppendLine("using System.Text.Json;")
            .Append(namespaceName == "HPD.Agent.Client" ? string.Empty : "using HPD.Agent.Client;\n")
            .AppendLine()
            .Append("namespace ").Append(namespaceName).AppendLine(";")
            .AppendLine();

        RenderContractMetadata(builder);
        RenderSseTypes(builder);
        RenderPermissionHelpers(builder);
        RenderLiveEventsClient(builder);
        RenderThreadMessageProjection(builder);
        if (hasChat)
            RenderChatClient(builder);
        RenderRootClient(builder, hasChat);
        return builder.ToString();
    }

    private void RenderPermissionHelpers(StringBuilder builder)
    {
        var requestVariant = EventVariantOrDefault(
            variant => string.Equals(
                variant.Discriminator,
                "PERMISSION_REQUEST",
                StringComparison.Ordinal));
        var responseVariant = EventVariantOrDefault(
            variant => string.Equals(
                variant.Discriminator,
                "PERMISSION_RESPONSE",
                StringComparison.Ordinal));
        if (requestVariant is null || responseVariant is null)
            return;
        var requestType = names.ForComponent(requestVariant.ComponentId);
        var responseType = names.ForComponent(responseVariant.ComponentId);

        builder
            .AppendLine()
            .AppendLine("/// <summary>Generated helpers for the simple allow/deny permission surface.</summary>")
            .AppendLine("public static class HpdAgentPermissions")
            .AppendLine("{")
            .Append("    public static HpdAgentPermissionPrompt ToPrompt(")
            .Append(requestType).AppendLine(" request)")
            .AppendLine("    {")
            .AppendLine("        ArgumentNullException.ThrowIfNull(request);")
            .AppendLine("        return new HpdAgentPermissionPrompt(")
            .AppendLine("            request.PermissionId,")
            .AppendLine("            request.CallId,")
            .AppendLine("            request.FunctionName ?? request.Authority ?? \"unknown\",")
            .AppendLine("            request.Action,")
            .AppendLine("            request.Arguments ?? EmptyObject(),")
            .AppendLine("            request.Reason);")
            .AppendLine("    }")
            .AppendLine()
            .Append("    public static ").Append(responseType).AppendLine(" CreateResponse(")
            .Append(requestType).AppendLine(" request,")
            .AppendLine("        HpdAgentPermissionAnswer answer)")
            .AppendLine("    {")
            .AppendLine("        ArgumentNullException.ThrowIfNull(request);")
            .AppendLine("        ArgumentNullException.ThrowIfNull(answer);")
            .AppendLine("        if (!string.Equals(request.PermissionId, answer.PermissionId, StringComparison.Ordinal))")
            .AppendLine("            throw new InvalidOperationException(\"PermissionAnswerUnbound: permission ID does not match.\");")
            .AppendLine("        var requiredId = answer.Approved ? \"allow_once\" : \"deny_once\";")
            .AppendLine("        var choice = request.Choices.FirstOrDefault(candidate =>")
            .AppendLine("            string.Equals(candidate.Id, requiredId, StringComparison.Ordinal));")
            .AppendLine("        if (choice is null)")
            .AppendLine("            throw new InvalidOperationException($\"Simple permission answers require a declared '{requiredId}' choice.\");")
            .AppendLine("        return new " + responseType)
            .AppendLine("        {")
            .AppendLine("            PermissionId = request.PermissionId,")
            .AppendLine("            SourceName = request.SourceName,")
            .AppendLine("            ChoiceId = choice.Id,")
            .AppendLine("            Feedback = answer.Reason")
            .AppendLine("        };")
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    private static JsonElement EmptyObject()")
            .AppendLine("    {")
            .AppendLine("        using var document = JsonDocument.Parse(\"{}\");")
            .AppendLine("        return document.RootElement.Clone();")
            .AppendLine("    }")
            .AppendLine("}");
    }

