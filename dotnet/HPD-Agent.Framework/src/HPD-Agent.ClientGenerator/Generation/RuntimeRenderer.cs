    private void RenderRootClient(StringBuilder builder, bool hasChat)
    {
        var services = Services()
            .Select(static service => (
                Tag: service.Key,
                Name: service.Value,
                Property: service.Value.EndsWith("Client", StringComparison.Ordinal)
                    ? service.Value[..^"Client".Length]
                    : service.Value))
            .OrderBy(static service => service.Property, StringComparer.Ordinal)
            .ToArray();
        builder.AppendLine()
            .AppendLine("/// <summary>Root client for one generated HPD Agent application contract.</summary>")
            .AppendLine("public sealed class HpdAgentClient : HpdAgentClientBase")
            .AppendLine("{")
            .AppendLine("    public HpdAgentClient(HpdAgentClientOptions options)")
            .AppendLine("        : base(options)")
            .AppendLine("    {");
        foreach (var service in services)
        {
            builder.Append("        ").Append(service.Property)
                .Append(" = new ").Append(service.Name).AppendLine("(this);");
        }
        builder.AppendLine("        Live = new HpdAgentLiveEventsClient(this);");
        if (hasChat)
            builder.AppendLine("        Chat = new HpdAgentChatManager(this);");
        builder.AppendLine("    }");
        foreach (var service in services)
        {
            builder.Append("    public ").Append(service.Name).Append(' ')
                .Append(service.Property).AppendLine(" { get; }");
        }
        builder.AppendLine("    public HpdAgentLiveEventsClient Live { get; }");
        if (hasChat)
            builder.AppendLine("    public HpdAgentChatManager Chat { get; }");
        builder.AppendLine("}");
    }

    private bool CanRenderChat()
    {
        var requiredOperations = new[]
        {
            "CreateSession",
            "SearchSessions",
            "GetSession",
            "SubmitAgentInput",
            "GetAgentThreadRuntimeState",
            "CancelThreadExecution",
            "StartQueuedThreadWork",
            "ListThreadExecutions",
            "GetThreadExecution"
        };
        var createSession = ir.Operations.SingleOrDefault(static operation =>
            string.Equals(operation.OperationId, "CreateSession", StringComparison.Ordinal));
        return requiredOperations.All(id =>
                   ir.Operations.Any(operation =>
                       string.Equals(operation.OperationId, id, StringComparison.Ordinal))) &&
               createSession is not null &&
               names.ReferencedModelName(createSession.SuccessType) is not null &&
               names.ReferencedModelName(createSession.RequestBody?.Type) is not null &&
               PublicInputVariants().Any(static value =>
                   string.Equals(value.Discriminator, "USER_MESSAGES_INPUT", StringComparison.Ordinal)) &&
               PublicInputVariants().Any(static value =>
                   string.Equals(value.Discriminator, "CREATE_GOAL_INPUT", StringComparison.Ordinal)) &&
               PublicInputVariants().Any(static value =>
                   string.Equals(value.Discriminator, "COMPACT_THREAD_INPUT", StringComparison.Ordinal));
    }

