using System.Text;
using System.Text.Json;
using HPD.Agent.SDK.Contract;

namespace HPD.Agent.ClientGenerator.Generation;

internal sealed class ModelRenderer(
    HpdSdkIr ir,
    CSharpNames names,
    string namespaceName)
{
    public string RenderModels()
    {
        var eventUnion = Union("output-event");
        var publicInputUnion = Union("request-input");
        var responseInputUnion = ir.Unions.SingleOrDefault(static union =>
            string.Equals(union.Role, "interaction-response", StringComparison.Ordinal));
        var eventIds = eventUnion.Variants
            .Select(static value => value.ComponentId)
            .ToHashSet(StringComparer.Ordinal);
        var inputIds = publicInputUnion.Variants
            .Select(static value => value.ComponentId)
            .ToHashSet(StringComparer.Ordinal);
        var responseIds = (responseInputUnion?.Variants ?? [])
            .Select(static value => value.ComponentId)
            .ToHashSet(StringComparer.Ordinal);
        var builder = new StringBuilder()
            .AppendLine("// <auto-generated/>")
            .AppendLine("#nullable enable")
            .AppendLine("using System.Text.Json;")
            .AppendLine("using System.Text.Json.Serialization;")
            .Append(namespaceName == "HPD.Agent.Client" ? string.Empty : "using HPD.Agent.Client;\n")
            .AppendLine()
            .Append("namespace ").Append(namespaceName).AppendLine(";")
            .AppendLine();

        RenderUnionBase(builder, "HpdAgentEvent", eventUnion.Variants);
        builder.AppendLine();
        RenderUnionBase(builder, "HpdAgentInputEvent", publicInputUnion.Variants);
        if (responseInputUnion is { Variants.Count: > 0 })
        {
            builder.AppendLine();
            RenderUnionBase(
                builder,
                "HpdAgentResponseInput",
                responseInputUnion.Variants,
                "HpdAgentEvent");
        }
        foreach (var extensibleEnum in names.Enums)
        {
            builder.AppendLine();
            RenderExtensibleEnum(builder, extensibleEnum);
        }

        foreach (var pair in names.ModelNames.OrderBy(static pair => pair.Value, StringComparer.Ordinal))
        {
            builder.AppendLine();
            var type = names.Type(pair.Key);
            var baseType = responseIds.Contains(pair.Key)
                ? "HpdAgentResponseInput"
                : eventIds.Contains(pair.Key)
                    ? "HpdAgentEvent"
                : inputIds.Contains(pair.Key)
                    ? "HpdAgentInputEvent"
                    : null;
            RenderModel(
                builder,
                pair.Key,
                pair.Value,
                type,
                baseType,
                skipTypeProperty: baseType is not null);
        }
        return builder.ToString();
    }

    public string RenderJsonContext()
    {
        var builder = new StringBuilder()
            .AppendLine("// <auto-generated/>")
            .AppendLine("#nullable enable")
            .AppendLine("using System.Text.Json;")
            .AppendLine("using System.Text.Json.Serialization;")
            .Append(namespaceName == "HPD.Agent.Client" ? string.Empty : "using HPD.Agent.Client;\n")
            .AppendLine()
            .Append("namespace ").Append(namespaceName).AppendLine(";")
            .AppendLine()
            .AppendLine("[JsonSourceGenerationOptions(")
            .AppendLine("    PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase,")
            .AppendLine("    DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,")
            .AppendLine("    GenerationMode = JsonSourceGenerationMode.Default)]")
            .AppendLine("[JsonSerializable(typeof(HpdAgentEvent))]")
            .AppendLine("[JsonSerializable(typeof(HpdAgentInputEvent))]");
        if (UnionOrNull("interaction-response") is { Variants.Count: > 0 })
            builder.AppendLine("[JsonSerializable(typeof(HpdAgentResponseInput))]");
        builder
            .AppendLine("[JsonSerializable(typeof(HpdAgentResponseResult))]")
            .AppendLine("[JsonSerializable(typeof(HpdAgentResponseStatus))]")
            .AppendLine("[JsonSerializable(typeof(HpdAgentInputSubmissionResult))]")
            .AppendLine("[JsonSerializable(typeof(HpdAgentEventDelivery))]")
            .AppendLine("[JsonSerializable(typeof(HpdAgentRoute))]")
            .AppendLine("[JsonSerializable(typeof(HpdAgentThreadKey))]")
            .AppendLine("[JsonSerializable(typeof(JsonElement))]")
            .AppendLine("[JsonSerializable(typeof(Dictionary<string, JsonElement>))]");

        foreach (var modelName in names.ModelNames.Values.OrderBy(static value => value, StringComparer.Ordinal))
        {
            builder.Append("[JsonSerializable(typeof(").Append(modelName).AppendLine("))]");
            builder.Append("[JsonSerializable(typeof(List<").Append(modelName).AppendLine(">))]");
        }
        foreach (var enumName in names.Enums.Select(static value => value.Name)
                     .OrderBy(static value => value, StringComparer.Ordinal))
        {
            builder.Append("[JsonSerializable(typeof(").Append(enumName).AppendLine("))]");
            builder.Append("[JsonSerializable(typeof(List<").Append(enumName).AppendLine(">))]");
        }
        var mapTypes = ir.Operations
            .SelectMany(static operation => new HpdTypeIr?[]
            {
                operation.SuccessType,
                operation.RequestBody?.Type
            })
            .Where(static type => type is not null)
            .Select(type => names.MapType(type!).TrimEnd('?'))
            .Where(static type => type.StartsWith("Dictionary<", StringComparison.Ordinal))
            .Distinct(StringComparer.Ordinal)
            .OrderBy(static type => type, StringComparer.Ordinal);
        foreach (var mapType in mapTypes)
        {
            builder.Append("[JsonSerializable(typeof(").Append(mapType)
                .Append("), TypeInfoPropertyName = ")
                .Append(Quote(CSharpNames.TypeInfoName(mapType)))
                .AppendLine(")]");
        }
        builder.AppendLine("internal sealed partial class HpdAgentJsonContext : JsonSerializerContext;");
        return builder.ToString();
    }

    private void RenderUnionBase(
        StringBuilder builder,
        string name,
        IReadOnlyList<HpdUnionVariantIr> variants,
        string? baseType = null)
    {
        builder.AppendLine("[JsonPolymorphic(")
            .AppendLine("    TypeDiscriminatorPropertyName = \"type\",")
            .AppendLine("    UnknownDerivedTypeHandling = JsonUnknownDerivedTypeHandling.FailSerialization)]");
        foreach (var variant in variants.OrderBy(static value => value.Discriminator, StringComparer.Ordinal))
        {
            builder
                .Append("[JsonDerivedType(typeof(")
                .Append(TypeIdentifier(variant.ComponentId))
                .Append("), ")
                .Append(Quote(variant.Discriminator))
                .AppendLine(")]");
        }
        builder.Append("public abstract partial record ").Append(name);
        if (baseType is not null)
            builder.Append(" : ").Append(baseType);
        builder.AppendLine(";");
    }

    private void RenderModel(
        StringBuilder builder,
        string componentId,
        string modelName,
        HpdTypeIr type,
        string? baseType,
        bool skipTypeProperty)
    {
        builder.Append("public sealed partial record ").Append(modelName);
        if (baseType is not null)
            builder.Append(" : ").Append(baseType);
        builder.AppendLine().AppendLine("{");

        var usedPropertyNames = new HashSet<string>(StringComparer.Ordinal);
        if (type.Properties is { Count: > 0 } properties)
        {
            foreach (var property in properties)
            {
                if (skipTypeProperty &&
                    string.Equals(property.Name, "type", StringComparison.Ordinal))
                {
                    continue;
                }

                var propertyName = UniquePropertyName(
                    CSharpNames.PropertyIdentifier(property.Name),
                    usedPropertyNames);
                var propertyType = names.MapPropertyType(
                    componentId,
                    propertyName: property.Name,
                    optional: !property.Required);
                builder.Append("    [JsonPropertyName(").Append(Quote(property.Name)).AppendLine(")]")
                    .Append("    public ");
                if (property.Required)
                    builder.Append("required ");
                builder.Append(propertyType).Append(' ').Append(propertyName).AppendLine(" { get; init; }");
                builder.AppendLine();
            }
        }

        if (type.AllowsAdditionalProperties)
        {
            builder.AppendLine("    [JsonExtensionData]")
                .Append("    public Dictionary<string, JsonElement>")
                .AppendLine(">? AdditionalProperties { get; init; }");
        }
        builder.AppendLine("}");
    }

    private static string UniquePropertyName(string candidate, HashSet<string> used)
    {
        if (used.Add(candidate))
            return candidate;
        for (var suffix = 2; ; suffix++)
        {
            var next = candidate + suffix;
            if (used.Add(next))
                return next;
        }
    }

    private string TypeIdentifier(string componentId) => names.ForComponent(componentId);

    private HpdUnionIr Union(string role) =>
        UnionOrNull(role)
        ?? throw new InvalidOperationException($"IR has no '{role}' union.");

    private HpdUnionIr? UnionOrNull(string role) =>
        ir.Unions.SingleOrDefault(union =>
            string.Equals(union.Role, role, StringComparison.Ordinal));

    private static void RenderExtensibleEnum(
        StringBuilder builder,
        ExtensibleEnum extensibleEnum)
    {
        var members = new HashSet<string>(StringComparer.Ordinal);
        var pairs = extensibleEnum.Values
            .Select(value => (Value: value, Member: UniqueMember(CSharpNames.TypeIdentifier(value), members)))
            .ToArray();
        builder.Append("[JsonConverter(typeof(").Append(extensibleEnum.Name).AppendLine("JsonConverter))]")
            .Append("public readonly partial record struct ").Append(extensibleEnum.Name).AppendLine("(string Value)")
            .AppendLine("{");
        foreach (var pair in pairs)
        {
            builder.Append("    public static ").Append(extensibleEnum.Name).Append(' ')
                .Append(pair.Member).Append(" { get; } = new(")
                .Append(Quote(pair.Value)).AppendLine(");");
        }
        foreach (var pair in pairs)
        {
            builder.Append("    public bool Is").Append(pair.Member)
                .Append(" => string.Equals(Value, ").Append(Quote(pair.Value))
                .AppendLine(", StringComparison.Ordinal);");
        }
        builder.AppendLine("}");
        builder.Append("internal sealed class ").Append(extensibleEnum.Name).AppendLine("JsonConverter")
            .Append("    : JsonConverter<").Append(extensibleEnum.Name).AppendLine(">")
            .AppendLine("{")
            .Append("    public override ").Append(extensibleEnum.Name).AppendLine(" Read(")
            .AppendLine("        ref Utf8JsonReader reader,")
            .AppendLine("        Type typeToConvert,")
            .AppendLine("        JsonSerializerOptions options)")
            .AppendLine("    {")
            .AppendLine("        var value = reader.GetString();")
            .AppendLine("        return value is null")
            .AppendLine("            ? throw new JsonException(\"An extensible string enum value cannot be null.\")")
            .Append("            : new ").Append(extensibleEnum.Name).AppendLine("(value);")
            .AppendLine("    }")
            .AppendLine()
            .Append("    public override void Write(")
            .AppendLine("        Utf8JsonWriter writer,")
            .Append("        ").Append(extensibleEnum.Name).AppendLine(" value,")
            .AppendLine("        JsonSerializerOptions options) =>")
            .AppendLine("        writer.WriteStringValue(value.Value);")
            .AppendLine("}");
    }

    private static string UniqueMember(string candidate, HashSet<string> used)
    {
        if (used.Add(candidate))
            return candidate;
        for (var suffix = 2; ; suffix++)
        {
            var next = candidate + suffix;
            if (used.Add(next))
                return next;
        }
    }

    private static string Quote(string value) =>
        JsonSerializer.Serialize(value);
}
