using System.Text;
using Microsoft.CodeAnalysis;

namespace HPD.Agent.SourceGenerator.SourceGeneration;

/// <summary>Roots the optional MCP configuration activator in consuming applications.</summary>
[Generator]
public sealed class McpConfigurationCompositionGenerator : IIncrementalGenerator
{
    private const string PackageTypeName = "HPD.Agent.MCP.McpConfigurationPackage";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var referenced = context.CompilationProvider.Select(static (compilation, _) =>
        {
            var marker = compilation.GetTypeByMetadataName(PackageTypeName);
            return marker is not null &&
                !SymbolEqualityComparer.Default.Equals(marker.ContainingAssembly, compilation.Assembly);
        });
        context.RegisterSourceOutput(referenced, static (context, referenced) =>
        {
            if (!referenced)
                return;

            var source = new StringBuilder();
            source.AppendLine("// <auto-generated/>");
            source.AppendLine("namespace HPD.Agent.MCP.Generated;");
            source.AppendLine("internal static class McpConfigurationCompositionRegistration");
            source.AppendLine("{");
            source.AppendLine("#pragma warning disable CA2255");
            source.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
            source.AppendLine("    internal static void Register()");
            source.AppendLine("#pragma warning restore CA2255");
            source.AppendLine("        => global::HPD.Agent.MCP.McpConfigurationPackage.Register();");
            source.AppendLine("}");
            context.AddSource("McpConfigurationCompositionRegistration.g.cs", source.ToString());
        });
    }
}
