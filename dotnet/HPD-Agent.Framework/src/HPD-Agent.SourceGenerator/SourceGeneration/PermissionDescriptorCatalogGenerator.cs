using System.Text;
using Microsoft.CodeAnalysis;

namespace HPD.Agent.SourceGenerator.SourceGeneration;

/// <summary>Generates stable permission policy and interaction descriptor packages.</summary>
[Generator]
public sealed class PermissionDescriptorCatalogGenerator : IIncrementalGenerator
{
    private const string PolicyDefinitionAttribute =
        "HPD.Agent.Permissions.PermissionPolicyDefinitionAttribute";
    private const string InteractionDefinitionAttribute =
        "HPD.Agent.Permissions.PermissionInteractionDefinitionAttribute";
    private const string PackageAttribute =
        "HPD.Agent.Permissions.PermissionDescriptorPackageAttribute";
    private const string PolicyInterface =
        "HPD.Agent.Permissions.IPermissionPolicy";
    private const string InteractionInterface =
        "HPD.Agent.Permissions.IPermissionInteraction";
    private const string InteractionEventInterface =
        "HPD.Agent.Permissions.IPermissionInteractionEventContract`2";
    private const string PresentationAttribute =
        "HPD.Agent.Permissions.PermissionPresentationAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var model = context.CompilationProvider.Select(static (compilation, _) =>
            Analyze(compilation));
        context.RegisterSourceOutput(model, static (sourceContext, package) =>
        {
            foreach (var diagnostic in package.Diagnostics)
                sourceContext.ReportDiagnostic(diagnostic);
            sourceContext.AddSource(package.HintName, package.Source);
        });
    }

    private static GeneratedPackage Analyze(Compilation compilation)
    {
        var diagnostics = new List<Diagnostic>();
        var descriptors = new List<DescriptorModel>();
        var packageType = compilation.GetTypeByMetadataName(PackageAttribute);
        var referencedPackages = new List<INamedTypeSymbol>();
        foreach (var assembly in compilation.SourceModule.ReferencedAssemblySymbols)
        {
            foreach (var attribute in assembly.GetAttributes())
            {
                if (packageType is null ||
                    !SymbolEqualityComparer.Default.Equals(attribute.AttributeClass, packageType) ||
                    attribute.ConstructorArguments.FirstOrDefault().Value is not INamedTypeSymbol provider)
                    continue;
                if (!referencedPackages.Any(existing =>
                        SymbolEqualityComparer.Default.Equals(existing, provider)))
                    referencedPackages.Add(provider);
            }
        }

        VisitNamespace(compilation.Assembly.GlobalNamespace, descriptors, diagnostics, compilation);
        var ids = new Dictionary<string, ISymbol>(StringComparer.Ordinal);
        foreach (var descriptor in descriptors.ToArray())
        {
            if (ids.TryGetValue(descriptor.Id, out var existing))
            {
                diagnostics.Add(Diagnostic.Create(
                    PermissionCatalogDiagnostics.DuplicateId,
                    descriptor.Location,
                    descriptor.Id,
                    existing.ToDisplayString(),
                    descriptor.Type.ToDisplayString()));
                descriptors.Remove(descriptor);
            }
            else
            {
                ids.Add(descriptor.Id, descriptor.Type);
            }
        }

        var packageName = "PermissionDescriptorPackage_" +
            Sanitize(compilation.AssemblyName ?? "Assembly");
        var hasPackage = descriptors.Count > 0;
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#pragma warning disable CA2255");
        if (hasPackage)
        {
            source.Append("[assembly: global::HPD.Agent.Permissions.PermissionDescriptorPackageAttribute(typeof(global::")
                .Append(PackageNamespace)
                .Append('.')
                .Append(packageName)
                .AppendLine("))]");
        }
        source.Append("namespace ").Append(PackageNamespace).AppendLine(";");
        source.AppendLine();
        if (hasPackage)
        {
            source.Append("public sealed class ").Append(packageName)
                .AppendLine(" : global::HPD.Agent.Permissions.IPermissionDescriptorPackage");
            source.AppendLine("{");
            source.Append("    public static ").Append(packageName).AppendLine(" Instance { get; } = new();");
            source.AppendLine(
                "    public global::System.Collections.Generic.IReadOnlyDictionary<string, " +
                "global::HPD.Agent.Permissions.AIFunctionPermissionDescriptor> Descriptors { get; } =");
            source.AppendLine(
                "        new global::System.Collections.Generic.Dictionary<string, " +
                "global::HPD.Agent.Permissions.AIFunctionPermissionDescriptor>(global::System.StringComparer.Ordinal)");
            source.AppendLine("        {");
            foreach (var descriptor in descriptors)
                source.Append("            [").Append(Literal(descriptor.Id)).Append("] = ")
                    .Append(descriptor.Initializer).AppendLine(",");
            source.AppendLine("        };");
            source.AppendLine("}");
            source.AppendLine();
        }

        source.Append("internal static class ").Append(packageName).AppendLine("Registration");
        source.AppendLine("{");
        source.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        source.AppendLine("    internal static void Register()");
        source.AppendLine("    {");
        if (hasPackage)
            source.Append("        global::HPD.Agent.Permissions.PermissionDescriptorComposition.Register(")
                .Append(packageName).AppendLine(".Instance);");
        foreach (var provider in referencedPackages)
        {
            source.Append("        global::HPD.Agent.Permissions.PermissionDescriptorComposition.Register(")
                .Append(provider.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
                .AppendLine(".Instance);");
        }
        source.AppendLine("    }");
        source.AppendLine("}");
        source.AppendLine("#pragma warning restore CA2255");

        return new GeneratedPackage(
            "PermissionDescriptorCatalog.g.cs",
            source.ToString(),
            diagnostics.ToArray());
    }

    private static void VisitNamespace(
        INamespaceSymbol @namespace,
        List<DescriptorModel> descriptors,
        List<Diagnostic> diagnostics,
        Compilation compilation)
    {
        foreach (var type in @namespace.GetTypeMembers())
            VisitType(type);
        foreach (var child in @namespace.GetNamespaceMembers())
            VisitNamespace(child, descriptors, diagnostics, compilation);
        return;

        void VisitType(INamedTypeSymbol type)
        {
            AnalyzeType(type);
            foreach (var child in type.GetTypeMembers())
                VisitType(child);
        }

        void AnalyzeType(INamedTypeSymbol type)
        {
            var policyAttribute = FindAttribute(type, PolicyDefinitionAttribute, compilation);
            var interactionAttribute = FindAttribute(type, InteractionDefinitionAttribute, compilation);
            if (policyAttribute is null && interactionAttribute is null)
                return;
            var location = type.Locations.FirstOrDefault() ?? Location.None;
            if (policyAttribute is not null && interactionAttribute is not null)
            {
                diagnostics.Add(Diagnostic.Create(
                    PermissionCatalogDiagnostics.MultipleDefinitions,
                    location,
                    type.ToDisplayString()));
                return;
            }
            if (type.IsAbstract || type.IsGenericType)
            {
                diagnostics.Add(Diagnostic.Create(
                    PermissionCatalogDiagnostics.InvalidDefinitionType,
                    location,
                    type.ToDisplayString(),
                    "abstract or generic"));
                return;
            }

            var attribute = policyAttribute ?? interactionAttribute!;
            var id = attribute.ConstructorArguments.FirstOrDefault().Value as string;
            var reservedFrameworkId = id?.StartsWith("hpd.", StringComparison.OrdinalIgnoreCase) == true &&
                compilation.AssemblyName?.StartsWith("HPD-Agent", StringComparison.Ordinal) != true;
            if (string.IsNullOrWhiteSpace(id) || id != id.Trim() || id.Any(char.IsControl) ||
                reservedFrameworkId)
            {
                diagnostics.Add(Diagnostic.Create(
                    PermissionCatalogDiagnostics.InvalidId,
                    location,
                    id ?? "<null>",
                    type.ToDisplayString()));
                return;
            }

            if (policyAttribute is not null)
            {
                var policyContract = compilation.GetTypeByMetadataName(PolicyInterface);
                if (policyContract is null || !Implements(type, policyContract))
                {
                    diagnostics.Add(Diagnostic.Create(
                        PermissionCatalogDiagnostics.InvalidDefinitionType,
                        location,
                        type.ToDisplayString(),
                        "IPermissionPolicy"));
                    return;
                }
                var initializer = CreatePolicyDescriptor(id!, type);
                if (initializer is null)
                {
                    diagnostics.Add(Diagnostic.Create(
                        PermissionCatalogDiagnostics.InvalidPresentation,
                        location,
                        type.ToDisplayString()));
                    return;
                }
                descriptors.Add(new(id!, type, location, initializer));
                return;
            }

            var interactionContract = compilation.GetTypeByMetadataName(InteractionInterface);
            if (interactionContract is null || !Implements(type, interactionContract))
            {
                diagnostics.Add(Diagnostic.Create(
                    PermissionCatalogDiagnostics.InvalidDefinitionType,
                    location,
                    type.ToDisplayString(),
                    "IPermissionInteraction"));
                return;
            }
            var expectedEventContract = compilation.GetTypeByMetadataName(InteractionEventInterface);
            var eventContract = type.AllInterfaces.FirstOrDefault(candidate =>
                candidate.IsGenericType &&
                expectedEventContract is not null &&
                SymbolEqualityComparer.Default.Equals(
                    candidate.OriginalDefinition, expectedEventContract));
            if (eventContract is null || eventContract.TypeArguments.Length != 2)
            {
                diagnostics.Add(Diagnostic.Create(
                    PermissionCatalogDiagnostics.InvalidInteraction,
                    location,
                    type.ToDisplayString()));
                return;
            }

            descriptors.Add(new(
                id!,
                type,
                location,
                CreateInteractionDescriptor(id!, type, eventContract)));
        }
    }

    private static string? CreatePolicyDescriptor(string id, INamedTypeSymbol type)
    {
        var factory = CreateFactory("PolicyFactory", type);
        var presentation = CreatePresentationDescriptor(type);
        return
            "new global::HPD.Agent.Permissions.AIFunctionPermissionDescriptor { " +
            $"DescriptorId = {Literal(id)}, {factory} {presentation}" +
            " }";
    }

    private static string CreateInteractionDescriptor(
        string id,
        INamedTypeSymbol type,
        INamedTypeSymbol contract) =>
        "new global::HPD.Agent.Permissions.AIFunctionPermissionDescriptor { " +
        $"DescriptorId = {Literal(id)}, {CreateFactory("InteractionFactory", type)} " +
        $"RequestEventType = typeof({contract.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}), " +
        $"ResponseEventType = typeof({contract.TypeArguments[1].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}) " +
        "}";

    private static string CreateFactory(string property, INamedTypeSymbol type)
    {
        var typeName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        if (type.InstanceConstructors.Any(static constructor =>
                constructor.Parameters.Length == 0 &&
                constructor.DeclaredAccessibility is Accessibility.Public or Accessibility.Internal))
            return $"{property} = static _ => new {typeName}(),";
        var serviceType = property == "PolicyFactory"
            ? "HPD.Agent.Permissions.IPermissionPolicy"
            : "HPD.Agent.Permissions.IPermissionInteraction";
        return
            $"{property} = static services => (global::{serviceType})(services.GetService(typeof({typeName})) ?? " +
            $"throw new global::System.InvalidOperationException(\"Permission service '{typeName}' is not registered.\")),";
    }

    private static string CreatePresentationDescriptor(INamedTypeSymbol policyType)
    {
        for (var current = policyType; current is not null; current = current.BaseType)
        {
            if (!current.IsGenericType || current.Name != "PermissionPolicy" ||
                current.TypeArguments.Length != 1)
                continue;
            var presentation = current.TypeArguments[0];
            var attribute = presentation.GetAttributes().FirstOrDefault(attribute =>
                attribute.AttributeClass?.ToDisplayString() == PresentationAttribute);
            if (attribute is null)
                return string.Empty;
            var id = attribute.ConstructorArguments.FirstOrDefault().Value as string;
            if (string.IsNullOrWhiteSpace(id) ||
                attribute.ConstructorArguments.Length < 2 ||
                attribute.ConstructorArguments[1].Value is not INamedTypeSymbol context)
                return string.Empty;
            var typeName = presentation.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var contextName = context.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var typeInfo =
                $"global::HPD.Agent.Permissions.PermissionPresentationDescriptor.RequireGeneratedJsonTypeInfo(" +
                $"{contextName}.Default.Options, typeof({typeName}), {Literal(id)})";
            return
                "Presentation = new global::HPD.Agent.Permissions.PermissionPresentationDescriptor { " +
                $"PresentationId = {Literal(id)}, PresentationType = typeof({typeName}), TypeInfo = {typeInfo}, " +
                $"Serialize = static value => global::System.Text.Json.JsonSerializer.SerializeToElement(value, {typeInfo}) }},";
        }
        return string.Empty;
    }

    private static AttributeData? FindAttribute(
        INamedTypeSymbol type,
        string metadataName,
        Compilation compilation)
    {
        var expected = compilation.GetTypeByMetadataName(metadataName);
        return expected is null
            ? null
            : type.GetAttributes().FirstOrDefault(attribute =>
                SymbolEqualityComparer.Default.Equals(attribute.AttributeClass, expected));
    }

    private static bool Implements(INamedTypeSymbol type, INamedTypeSymbol expected) =>
        SymbolEqualityComparer.Default.Equals(type, expected) ||
        type.AllInterfaces.Any(candidate =>
            SymbolEqualityComparer.Default.Equals(candidate, expected));

    private static string Sanitize(string value)
    {
        var result = new string(value.Select(character =>
            char.IsLetterOrDigit(character) ? character : '_').ToArray());
        return result.Length == 0 || char.IsDigit(result[0]) ? "_" + result : result;
    }

    private static string Literal(string value) =>
        "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    private const string PackageNamespace = "HPD.Agent.Permissions.Generated";

    private sealed record GeneratedPackage(
        string HintName,
        string Source,
        IReadOnlyList<Diagnostic> Diagnostics);

    private sealed record DescriptorModel(
        string Id,
        INamedTypeSymbol Type,
        Location Location,
        string Initializer);
}

internal static class PermissionCatalogDiagnostics
{
    internal static readonly DiagnosticDescriptor DuplicateId = new(
        "HPDAG1001",
        "Duplicate permission descriptor ID",
        "Permission descriptor ID '{0}' is assigned by both '{1}' and '{2}'",
        "HPD.Permissions",
        DiagnosticSeverity.Error,
        true);

    internal static readonly DiagnosticDescriptor InvalidId = new(
        "HPDAG1002",
        "Invalid permission descriptor ID",
        "Permission descriptor ID '{0}' on '{1}' is invalid or uses the reserved hpd. prefix",
        "HPD.Permissions",
        DiagnosticSeverity.Error,
        true);

    internal static readonly DiagnosticDescriptor InvalidDefinitionType = new(
        "HPDAG1003",
        "Invalid permission definition type",
        "Permission definition type '{0}' must implement '{1}' and be concrete and non-generic",
        "HPD.Permissions",
        DiagnosticSeverity.Error,
        true);

    internal static readonly DiagnosticDescriptor MultipleDefinitions = new(
        "HPDAG1004",
        "Multiple permission definition kinds",
        "Type '{0}' cannot declare both a policy and an interaction definition",
        "HPD.Permissions",
        DiagnosticSeverity.Error,
        true);

    internal static readonly DiagnosticDescriptor InvalidPresentation = new(
        "HPDAG1005",
        "Invalid permission presentation",
        "Permission policy '{0}' has invalid or missing source-generated presentation metadata",
        "HPD.Permissions",
        DiagnosticSeverity.Error,
        true);

    internal static readonly DiagnosticDescriptor InvalidInteraction = new(
        "HPDAG1006",
        "Invalid permission interaction",
        "Permission interaction '{0}' must implement a closed IPermissionInteractionEventContract<TRequest, TResponse>",
        "HPD.Permissions",
        DiagnosticSeverity.Error,
        true);
}
